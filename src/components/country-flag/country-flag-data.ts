export type CountryFlagCode = (typeof COUNTRY_FLAG_CODES)[number];

export interface CountryFlagMetadata {
  height: number;
  offsetY: number;
  width: number;
}

const tallFlagCodes: ReadonlySet<CountryFlagCode> = new Set(['aq', 'me', 'n-a', 'unk']);

const narrowFlagWidths: Partial<Record<CountryFlagCode, number>> = {
  ch: 11,
  np: 9,
};

const countryFlagCodeSet: ReadonlySet<string> = new Set(COUNTRY_FLAG_CODES);

const countryFlagAliases: Readonly<Record<string, CountryFlagCode>> = {
  'n/a': 'n-a',
  uk: 'gb',
  unknown: 'unk',
};

let nextOffsetY = 0;

const countryFlagMetadata: ReadonlyMap<CountryFlagCode, CountryFlagMetadata> = new Map(
  COUNTRY_FLAG_CODES.map((code) => {
    const height = tallFlagCodes.has(code) ? 12 : 11;

    const metadata: CountryFlagMetadata = {
      height,
      offsetY: nextOffsetY,
      width: narrowFlagWidths[code] ?? 16,
    };

    nextOffsetY += height + 2;

    return [code, metadata] as const;
  }),
);

export function isCountryFlagCode(code: string): code is CountryFlagCode {
  return countryFlagCodeSet.has(code);
}

export function resolveCountryFlagCode(code: string | null | undefined): CountryFlagCode | null {
  const normalizedCode = code?.trim().toLowerCase();

  if (!normalizedCode) {
    return null;
  }

  const aliasedCode = countryFlagAliases[normalizedCode] ?? normalizedCode;

  return isCountryFlagCode(aliasedCode) ? aliasedCode : null;
}

export function getCountryFlagMetadata(code: CountryFlagCode): CountryFlagMetadata {
  const metadata = countryFlagMetadata.get(code);

  if (!metadata) {
    throw new Error(`Missing country flag metadata for "${code}".`);
  }

  return metadata;
}
